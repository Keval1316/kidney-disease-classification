def _predict_handler(image: Image.Image):
    """Run model inference on the uploaded CT slice and return probabilities and clinical report."""
    if image is None:
        return None, "### Please upload an image to analyze."

    try:
        result = predict_image(image)
        prediction = result["prediction"]
        confidence = result["confidence"]
        probabilities = result["probabilities"]

        details = CLINICAL_DETAILS.get(prediction, {})
        badge = details.get("badge", prediction)
        summary = details.get("summary", "")
        findings = details.get("findings", "")

        report_md = f"""
### Diagnostic Assessment: {badge}
- **Primary Prediction:** **{prediction}** ({confidence * 100:.2f}% Confidence)
- **Clinical Summary:** {summary}
- **Radiological Reference:** {findings}

---
*Generated by NephroScan AI Deep Learning Inference Engine (EfficientNetB0).*
"""
        return probabilities, report_md

    except Exception as exc:
        return None, f"**Error during inference:** {exc}"


if has_spaces:
    @spaces.GPU
    def classify_ct_scan(image: Image.Image):
        return _predict_handler(image)
else:
    def classify_ct_scan(image: Image.Image):
        return _predict_handler(image)


# Define sample images if available
SAMPLE_DIR = Path("app/samples")
examples = []
