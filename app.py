# Build Gradio Interface
with gr.Blocks(css=custom_css, title="NephroScan AI — CT Kidney Disease Classifier") as demo:
    with gr.Column(elem_id="main-container"):
        gr.Markdown("# 🫁 NephroScan AI: CT Kidney Disease Classification", elem_classes=["header-title"])
        gr.Markdown(
            "Deep Learning Diagnostic System powered by **EfficientNetB0** for automated classification of Axial Kidney CT Slices (**Normal, Cyst, Stone, Tumor**).",
            elem_classes=["header-sub"],
        )

        with gr.Row(elem_classes=["disclaimer-box"]):
            gr.Markdown(DISCLAIMER_TEXT)

        with gr.Row():
            with gr.Column(scale=1):
                input_image = gr.Image(type="pil", label="Upload Kidney CT Scan Image", sources=["upload", "clipboard"])
                predict_btn = gr.Button("🔍 Analyze CT Scan", variant="primary", size="lg")
                
                if examples:
                    gr.Examples(
                        examples=examples,
                        inputs=[input_image],
                        label="1-Click CT Scan Sample Presets",
                    )

            with gr.Column(scale=1):
                output_label = gr.Label(num_top_classes=4, label="Class Probabilities")
                output_report = gr.Markdown(label="Clinical Insight Report")

        predict_btn.click(
            fn=classify_ct_scan,
            inputs=[input_image],
            outputs=[output_label, output_report],
        )

if __name__ == "__main__":
    demo.launch()
